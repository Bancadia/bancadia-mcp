// Copies dev's registry data into bancadia-db's seed folder, so `npm run db:reset` rebuilds local as an exact
// copy of dev (migrations first, then this seed). Read-only against dev, over the REST API with the dev secret
// key, so no database password is needed.
//
//   node scripts/db/sync-from-dev.mjs          dump dev -> <bancadia-db>/supabase/seeds/dev-data.sql
//   node scripts/db/sync-from-dev.mjs --check  fail unless that file exists (used by db:reset)
//
// Needs DEV_SUPABASE_SECRET_KEY (same value as the CI secret) in the environment or the git-ignored .env.
// Only the registry tables below are copied. Everything else (auth, tokens, verifier tables, listing_sources)
// keeps what the migrations and seed-test-fixtures.mjs create.
import { createClient } from '@supabase/supabase-js'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseEnv } from 'node:util'
import { BANCADIA_DB_PATH } from './discover-env.mjs'

const DEV_URL = 'https://qbotkqtlyovicrpranqr.supabase.co'
const SEED = path.join(BANCADIA_DB_PATH, 'supabase/seeds/dev-data.sql')
const PAGE = 1000 // PostgREST's row cap on Supabase
// Parents first.
const TABLES = [
  'institutions',
  'integration_vocab',
  'limit_key_vocab',
  'business_deposit_accounts',
  'business_checking_details',
  'business_deposit_fees',
  'business_deposit_account_features',
  'business_deposit_feature_integrations',
  'business_deposit_plan_tiers',
  'business_deposit_promotions',
  'business_deposit_account_target_segments',
]

if (process.argv.includes('--check')) {
  if (!existsSync(SEED)) {
    console.error(`Missing ${SEED}. Run: npm run db:sync-from-dev (or npm run db:fresh)`)
    process.exit(1)
  }
  process.exit(0)
}

const fileEnv = existsSync('.env') ? parseEnv(readFileSync('.env', 'utf8')) : {}
const key = process.env.DEV_SUPABASE_SECRET_KEY ?? fileEnv.DEV_SUPABASE_SECRET_KEY
if (!key) {
  console.error('DEV_SUPABASE_SECRET_KEY (dev secret key) must be set in the environment or in .env')
  process.exit(1)
}

const dev = createClient(DEV_URL, key, { auth: { persistSession: false, autoRefreshToken: false } })
const data = {}
for (const t of TABLES) {
  const { data: rows, error } = await dev.from(t).select('*').range(0, PAGE - 1)
  if (error) throw new Error(`${t}: ${error.message}`)
  // shortcut: no pagination, so stop loudly if a table outgrows one page.
  if (rows.length >= PAGE) throw new Error(`${t} has ${PAGE}+ rows; add pagination to sync-from-dev.mjs`)
  data[t] = rows
}

// jsonb_populate_recordset restores column types and numeric scale (5 -> 5.00). Generated columns (the search
// vector) are left out of the column list so Postgres recomputes them.
const load = (t) => {
  const json = JSON.stringify(data[t])
  if (json.includes('$j$')) throw new Error(`${t}: data contains the dollar-quote tag`)
  return `DO $do$ DECLARE c text; BEGIN
SELECT string_agg(quote_ident(column_name), ',' ORDER BY ordinal_position) INTO c FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = '${t}' AND is_generated = 'NEVER';
EXECUTE format('INSERT INTO public.${t} (%1$s) SELECT %1$s FROM jsonb_populate_recordset(null::public.${t}, %2$L::jsonb)', c, $j$${json}$j$);
END $do$;`
}

mkdirSync(path.dirname(SEED), { recursive: true })
writeFileSync(
  SEED,
  [
    '-- Generated by scripts/db/sync-from-dev.mjs in bancadia-mcp. Do not edit or commit.',
    'BEGIN;',
    'SET session_replication_role = replica;',
    `TRUNCATE ${[...TABLES].reverse().map((t) => `public.${t}`).join(', ')} CASCADE;`,
    ...TABLES.map(load),
    'COMMIT;',
    '',
  ].join('\n')
)
console.log(`Wrote ${SEED}: ${TABLES.map((t) => `${t}=${data[t].length}`).join(', ')}`)
